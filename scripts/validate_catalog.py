#!/usr/bin/env python3
"""Validate marketplace structure and plugin-local resources without network access."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def inside(parent, value):
    path = (parent / value).resolve()
    if not path.is_relative_to(parent.resolve()):
        raise ValueError(f'Path escapes package: {value}')
    if not path.exists():
        raise ValueError(f'Missing file: {value}')
    return path


def validate():
    catalog = json.loads((ROOT / '.agents/plugins/marketplace.json').read_text())
    assert re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', catalog['name'])
    names = set()
    for entry in catalog['plugins']:
        name = entry['name']
        assert name not in names, f'Duplicate plugin: {name}'
        names.add(name)
        assert entry['source']['source'] == 'local'
        package = inside(ROOT, entry['source']['path'])
        manifest = json.loads((package / 'plugin.json').read_text())
        assert manifest['name'] == name
        assert manifest['$schema'] == 'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json'
        assert re.fullmatch(r'\d+\.\d+\.\d+', manifest['version'])
        settings = manifest.get('extensions', {}).get('com.openai', {})
        for key in ('composerIcon', 'logo'):
            inside(package, settings['interface'][key])
        if settings.get('onboardingSkill'):
            inside(package, settings['onboardingSkill'])
        skills = list((package / 'skills').glob('*/SKILL.md'))
        assert skills, f'No skills in {name}'
        for skill in skills:
            body = skill.read_text()
            front = re.match(r'\A---\n(.*?)\n---\n', body, re.S)
            assert front, f'Missing skill frontmatter: {skill}'
            assert re.search(r'^name: .+', front[1], re.M)
            assert re.search(r'^description: .+', front[1], re.M)
            assert 'TODO' not in body
        for file in package.rglob('*'):
            if not file.is_file():
                continue
            if '__pycache__' in file.parts or file.suffix == '.pyc':
                continue  # Generated by Python tests; ignored by Git and the ZIP builder.
            assert file.suffix != '.zip', f'Generated archive in source package: {file}'
            if file.suffix in {'.md', '.json', '.mjs', '.py', '.yaml'}:
                content = file.read_text()
                assert not any(token in content for token in ('/Users/', '/home/', 'C:\\Users\\'))
                assert not re.search(r'page_[0-9a-f]{20,}', content), f'Private Page ID: {file}'
        print(f'{name} {manifest["version"]}: {len(skills)} skills validated')
    assert names, 'Empty marketplace'


if __name__ == '__main__':
    validate()
